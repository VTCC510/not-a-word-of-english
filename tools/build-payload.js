'use strict';

/**
 * tools/build-payload.js
 * 词库安全校验器与自包含注入载荷构建器。
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const asar = require('./asar-lite');

const ROOT_DIR = path.resolve(__dirname, '..');
const DICT_DIR = path.join(ROOT_DIR, 'dict');
const SRC_DIR = path.join(ROOT_DIR, 'src');

const MAIN_HOOK_MARKER = '/* [NAWE-MAIN-HOOK-BEGIN] */';
const PRELOAD_MARKER = '/* [NAWE-PRELOAD-ENGINE-BEGIN] */';

function loadJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

/**
 * 校验全部词典与安全规则：确保无坏正则、高风险双语词条均保留英文、受保护斜杠指令未被误改。
 */
function loadAndValidateDictionaries(dictDir = DICT_DIR) {
  const nativeMenu = loadJson(path.join(dictDir, 'native-menu.json'));
  const sandboxRules = loadJson(path.join(dictDir, 'sandbox-rules.json'));
  const highRiskBilingual = loadJson(path.join(dictDir, 'high-risk-bilingual.json'));
  const uiStatic = loadJson(path.join(dictDir, 'ui-static.json'));
  const uiPatterns = loadJson(path.join(dictDir, 'ui-patterns.json'));

  for (const [en, zh] of Object.entries(highRiskBilingual.exact || {})) {
    if (!/[A-Za-z]/.test(zh)) {
      throw new Error(
        `安全校验失败：high-risk-bilingual.json 中 "${en}" 的译文 "${zh}" 未保留英文原文！`
      );
    }
  }

  const protectedCmds = new Set(
    (sandboxRules.preservedSlashCommands || []).map((c) => `/${String(c).toLowerCase()}`)
  );
  for (const key of Object.keys(uiStatic.exact || {})) {
    if (protectedCmds.has(key.trim().toLowerCase())) {
      throw new Error(
        `安全校验失败：ui-static.json 禁止直接翻译受保护的斜杠指令 "${key}"！`
      );
    }
  }

  const allPatternLists = [
    nativeMenu.menuPatterns,
    nativeMenu.dialogs && nativeMenu.dialogs.patterns,
    highRiskBilingual.patterns,
    uiPatterns.patterns,
  ];
  for (const list of allPatternLists) {
    if (!Array.isArray(list)) continue;
    for (const item of list) {
      try {
        new RegExp(item.pattern, item.flags || '');
      } catch (err) {
        throw new Error(`词库正则表达式无效 "${item.pattern}": ${err.message}`);
      }
    }
  }

  return {
    nativeMenu,
    sandboxRules,
    highRiskBilingual,
    uiStatic,
    uiPatterns,
  };
}

function buildMainHookModuleSource(dicts) {
  const mainHookSrc = fs.readFileSync(path.join(SRC_DIR, 'main-hook.js'), 'utf8');
  return [
    '/* Auto-generated by not-a-word-of-english (zero external dependencies) */',
    mainHookSrc,
    '',
    'const NAWE_NATIVE_DICT = ' + JSON.stringify(dicts.nativeMenu) + ';',
    'exports.boot = function bootNaweMainHook(electron) {',
    '  try {',
    '    return exports.installMainHook(electron, NAWE_NATIVE_DICT);',
    '  } catch (_) {',
    '    return { installed: false, reason: "caught-error" };',
    '  }',
    '};',
    '',
  ].join('\n');
}

function buildPreloadInjectionSource(dicts, { version = '1.0.0' } = {}) {
  const domEngineSrc = fs.readFileSync(path.join(SRC_DIR, 'dom-engine.js'), 'utf8');
  const rendererBundle = {
    sandboxRules: dicts.sandboxRules,
    highRiskBilingual: dicts.highRiskBilingual,
    uiStatic: dicts.uiStatic,
    uiPatterns: dicts.uiPatterns,
  };
  return [
    '',
    PRELOAD_MARKER,
    ';(function nawePreloadBootstrap() {',
    '  try {',
    '    var __naweExports = {};',
    '    var __naweModule = { exports: __naweExports };',
    '    (function (module, exports) {',
    domEngineSrc,
    '    })(__naweModule, __naweExports);',
    '    var __naweBundle = ' + JSON.stringify(rendererBundle) + ';',
    '    var __naweOpts = ' + JSON.stringify({ version: String(version) }) + ';',
    '    if (typeof window !== "undefined" && __naweModule.exports && typeof __naweModule.exports.installDomEngine === "function") {',
    '      __naweModule.exports.installDomEngine(window, __naweBundle, __naweOpts);',
    '    }',
    '  } catch (_) {',
    '    // 安全熔断：渲染层注入异常时静默降级为官方原版',
    '  }',
    '})();',
    '/* [NAWE-PRELOAD-ENGINE-END] */',
    '',
  ].join('\n');
}

function patchMainJsSource(origMainJs) {
  if (origMainJs.includes(MAIN_HOOK_MARKER)) {
    throw new Error('源 dist/main.js 已包含主进程注入标记，中止以防重复叠加。');
  }
  const injectLine =
    `${MAIN_HOOK_MARKER} try { require('./nawe-main-hook').boot(require('electron')); } catch (_) {} /* [NAWE-MAIN-HOOK-END] */\n`;

  const strictMatch = origMainJs.match(/^(\s*['"]use strict['"];?\r?\n)/);
  if (strictMatch) {
    return strictMatch[1] + injectLine + origMainJs.slice(strictMatch[1].length);
  }
  return injectLine + origMainJs;
}

function buildModifications(sourceAsarPath, options = {}) {
  const dicts = loadAndValidateDictionaries();
  const modifications = new Map();

  const origMain = asar.readFileText(sourceAsarPath, 'dist/main.js');
  if (!origMain) {
    throw new Error('源 app.asar 中未找到 dist/main.js，客户端结构可能已变化。');
  }
  modifications.set('dist/nawe-main-hook.js', buildMainHookModuleSource(dicts));
  modifications.set('dist/main.js', patchMainJsSource(origMain));

  const origPreload = asar.readFileText(sourceAsarPath, 'dist/preload.js');
  if (!origPreload) {
    throw new Error('源 app.asar 中未找到 dist/preload.js，客户端结构可能已变化。');
  }
  if (origPreload.includes(PRELOAD_MARKER)) {
    throw new Error('源 dist/preload.js 已包含渲染层注入标记，中止以防重复叠加。');
  }
  const preloadPayload = buildPreloadInjectionSource(dicts, options);
  modifications.set('dist/preload.js', origPreload + preloadPayload);

  const origWizardPreload = asar.readFileText(sourceAsarPath, 'dist/ideInstall/wizardPreload.js');
  if (origWizardPreload && !origWizardPreload.includes(PRELOAD_MARKER)) {
    modifications.set('dist/ideInstall/wizardPreload.js', origWizardPreload + preloadPayload);
  }

  const origSshPromptPreload = asar.readFileText(sourceAsarPath, 'dist/remote/sshPromptPreload.js');
  if (origSshPromptPreload && !origSshPromptPreload.includes(PRELOAD_MARKER)) {
    modifications.set('dist/remote/sshPromptPreload.js', origSshPromptPreload + preloadPayload);
  }

  return modifications;
}

/**
 * 离线词典与载荷完整性安检（供 `node cli.js check` 使用）。
 */
function runFullAudit(dictDir = DICT_DIR) {
  const dicts = loadAndValidateDictionaries(dictDir);
  const hrKeys = new Set(Object.keys(dicts.highRiskBilingual.exact || {}));
  const overlap = Object.keys(dicts.uiStatic.exact || {}).filter((k) => hrKeys.has(k));

  const mainSrc = buildMainHookModuleSource(dicts);
  const preloadSrc = buildPreloadInjectionSource(dicts, { version: 'audit' });
  new vm.Script(mainSrc, { filename: 'dist/nawe-main-hook.js' });
  new vm.Script(preloadSrc, { filename: 'dist/preload.js' });

  if (/\brequire\s*\(/.test(preloadSrc)) {
    throw new Error('安全审计失败：渲染层注入脚本中检测到 require() 调用。');
  }

  return {
    ok: true,
    counts: {
      nativeMenuLabels: Object.keys(dicts.nativeMenu.menuLabels || {}).length,
      nativeMenuPatterns: (dicts.nativeMenu.menuPatterns || []).length,
      nativeDialogsExact: Object.keys((dicts.nativeMenu.dialogs && dicts.nativeMenu.dialogs.exact) || {}).length,
      nativeDialogsBilingual: Object.keys((dicts.nativeMenu.dialogs && dicts.nativeMenu.dialogs.bilingualConfirm) || {}).length,
      highRiskExact: Object.keys(dicts.highRiskBilingual.exact || {}).length,
      highRiskPatterns: (dicts.highRiskBilingual.patterns || []).length,
      uiStaticExact: Object.keys(dicts.uiStatic.exact || {}).length,
      uiPatterns: (dicts.uiPatterns.patterns || []).length,
      preservedSlashCommands: (dicts.sandboxRules.preservedSlashCommands || []).length,
    },
    overlapWithHighRisk: overlap,
    payloadSizes: {
      mainHookBytes: Buffer.byteLength(mainSrc, 'utf8'),
      preloadBytes: Buffer.byteLength(preloadSrc, 'utf8'),
    },
  };
}

module.exports = {
  loadAndValidateDictionaries,
  buildMainHookModuleSource,
  buildPreloadInjectionSource,
  patchMainJsSource,
  buildModifications,
  runFullAudit,
};
